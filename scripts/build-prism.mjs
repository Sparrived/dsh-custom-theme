// Every preset ships as standalone CSS so it works with older theme loaders too.
import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../themes/', import.meta.url)
const source = await readFile(new URL('prism.css', root), 'utf8')
const boundary = source.indexOf('/* Keep layout')
if (boundary < 0) throw new Error('Prism component stylesheet not found')
const components = source.slice(boundary).replaceAll('\r\n', '\n')

// canvas, sidebar, surface, well, raised, popup, edge, divider, strong edge,
// ink, secondary ink, muted ink, accent, accent hover, on accent, tint, pressed, ring
const palettes = {
  'prism-obsidian': [
    ['#f5f8fc', '#e9eff7', '#ffffff', '#eaf0f7', '#ffffff', '#ffffff', '#dce5f0', '#cbd7e8', '#a6b6cb', '#18283e', '#465a72', '#54677e', '#2254a1', '#194585', '#ffffff', '#e2ecfb', '#d4e4fa', '#3164b5'],
    ['#101217', '#0d0f14', '#191e28', '#1c222d', '#252e3d', '#202834', '#2c3647', '#3a465b', '#60718a', '#eaf0fa', '#b4c3d9', '#98a9c0', '#a5c7ff', '#c4dbff', '#152441', '#253955', '#2c4364', '#8cb9fc'],
  ],
  'prism-alabaster': [
    ['#f7f4ed', '#ede8de', '#fdfbf7', '#f0eae0', '#fdfbf7', '#fffcf7', '#e5dbcc', '#d7cabb', '#b7a797', '#29211b', '#5b4d41', '#695b50', '#8a461f', '#733715', '#ffffff', '#f2e1d0', '#ebd5be', '#a35c34'],
    ['#191714', '#141310', '#24211d', '#28241f', '#332b24', '#2d2721', '#392f28', '#4a3c32', '#766154', '#f4eee7', '#cbbeb2', '#b4a499', '#f4bc88', '#ffd5ae', '#382314', '#493225', '#583e2c', '#e59e67'],
  ],
}

function tokens(colors, dark) {
  const [base, sidebar, surface, well, raised, popup, edge, divider, strong, ink, secondary, muted, accent, hover, onAccent, tint, pressed, ring] = colors
  const quiet = ink + (dark ? '17' : '12')
  const aliases = {
    'bg-base': base, 'bg-layer-1': surface, 'bg-layer-2': well, 'bg-layer-3': raised, 'bg-overlay': popup,
    'border-l1': edge, 'border-l2': divider, 'border-l2-darkmode-thin': edge, 'border-l3': strong,
    'label-primary': ink, 'label-secondary': secondary, 'label-tertiary': muted, 'label-caption': muted,
    'brand-primary': accent, 'brand-primary-new-colorprimary-new-color': accent, 'brand-text': onAccent,
    'button-primary-fill': accent, 'button-primary-hover': hover, 'button-primary-dimmed': divider,
    'button-info-fill': accent, 'button-info-hover': hover,
    'state-business-primary': accent, 'state-business-tertiary': tint,
    'button-ghost-active-border': ring, 'button-ghost-active-fill': tint, 'button-ghost-active-hover': pressed,
    'interactive-bg-hover': quiet, 'interactive-bg-hover-solid': well,
    'interactive-bg-hover-accent': accent + (dark ? '24' : '17'), 'interactive-bg-active': pressed, link: accent,
    'markdown-code-block': well, 'markdown-code-block-banner': divider, 'markdown-inline-code': tint,
    'menu-group-header-fill': popup,
  }
  const specific = {
    'sidebar-fill': sidebar, 'sidebar-nav-item-active': tint, 'sidebar-nav-item-active-accent': tint,
    'sidebar-nav-item-hover': quiet, 'input-major': surface, menu: popup, bubble: tint, 'bubble-highlight': pressed,
  }
  return [
    ...Object.entries(aliases).map(([key, value]) => ['dsw-alias-' + key, value]),
    ...Object.entries(specific).map(([key, value]) => ['dsw-specific-' + key, value]),
    ['dsw-menu-surface-fill', popup],
    ['dct-prism-ring', ring],
    ['dct-prism-lift', dark ? 'inset 0 1px #ffffff0a, 0 4px 14px #00000045' : '0 1px 2px #17203213, 0 5px 16px #1720320a'],
    ['dct-prism-popup', dark ? '0 2px 6px #00000050, 0 12px 32px #00000080' : '0 2px 6px #17203214, 0 12px 32px #17203223'],
    // Asks the plugin's composer focus ring on; absent in every other theme.
    ['dct-focus-grow', '1'],
  ].map(([key, value]) => '  --' + key + ': ' + value + ';').join('\n')
}

for (const [id, [light, dark]] of Object.entries(palettes)) {
  const path = new URL(id + '.css', root)
  const css = '/* Generated by scripts/build-prism.mjs; shared component rules from prism.css. */\n' +
    ':root {\n' + tokens(light, false) + '\n}\n\n' +
    ':root[data-theme="dark"] {\n' + tokens(dark, true) + '\n}\n\n' + components
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')).replaceAll('\r\n', '\n') !== css) throw new Error(id + '.css is stale; run npm run build:themes')
  } else await writeFile(path, css)
}
